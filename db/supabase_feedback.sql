-- ------------------------------------------------------------
-- 4. 行级安全（RLS）—— 这一步不做，你的反馈会被任何人读走
-- ------------------------------------------------------------
alter table public.feedback enable row level security;

-- 匿名访客（页面里的 anon key）：只允许"提交"，并且只能提交 new 状态的记录
drop policy if exists "anon can submit feedback" on public.feedback;
create policy "anon can submit feedback"
    on public.feedback
    for insert
    to anon
    with check (status = 'new');

-- ⚠️ 这里【故意不创建】select 策略。
--    PostgreSQL 的 RLS 是"默认拒绝"：没有 select 策略 = 匿名角色读不到任何一行。
--    因此即使 anon key 公开在网页源码里，别人也无法把你的反馈读走。
--    你自己在 Supabase 控制台（Table Editor）看数据不受 RLS 限制。


-- ------------------------------------------------------------
-- 4.5 明确授予匿名角色「最小必要权限」
--     Supabase 部分新项目不再自动给 public 架构里的表授予 anon 表级权限，
--     缺少这一步时页面提交会报 42501「permission denied for table feedback」。
--     这里【只授 insert】—— 不授 select / update / delete，
--     等于在 RLS 之外再加一层表级权限保护。
-- ------------------------------------------------------------
grant usage  on schema public          to anon;
grant insert on table public.feedback  to anon;


-- ------------------------------------------------------------
-- 5. 如果表是【更早版本】建的（还没有 relation / device 两列）
--    —— 执行下面两行即可补上，不影响已有数据。建表语句里已有这两列的话，跳过即可。
-- ------------------------------------------------------------
alter table public.feedback add column if not exists relation text;
alter table public.feedback add column if not exists device   text;


-- ------------------------------------------------------------
-- 6. 建好后自检（可选）：确认表、字段、索引、策略都在位
-- ------------------------------------------------------------
select
    (select count(*) from information_schema.tables
      where table_schema = 'public' and table_name = 'feedback')  as table_ok,
    (select count(*) from information_schema.columns
      where table_schema = 'public' and table_name = 'feedback'
        and column_name in ('name', 'relation', 'device', 'message', 'created_at')) as five_fields_ok,
    (select count(*) from pg_indexes
      where schemaname = 'public' and tablename = 'feedback')     as index_count,
    (select count(*) from pg_policies
      where schemaname = 'public' and tablename = 'feedback')     as policy_count,
    (select relrowsecurity from pg_class
      where oid = 'public.feedback'::regclass)                    as rls_enabled;
