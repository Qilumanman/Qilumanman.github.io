-- ------------------------------------------------------------
-- 1. feedback：访客意见反馈表
-- ------------------------------------------------------------
create table if not exists public.feedback (
    id          bigint      generated by default as identity primary key,  -- 主键，自增
    name        text,                                                      -- ① 名字或昵称（可选）
    relation    text,                                                      -- ② 与主页主人的关系（可选）
    device      text,                                                      -- ③ 本条反馈针对的设备（可选）
    contact     text,                                                      -- 邮箱/微信（可选）
    category    text        not null default 'other',                      -- 反馈类型
    rating      smallint,                                                  -- 满意度 1-5（可选）
    message     text        not null,                                      -- ④ 反馈正文（必填）
    page_url    text,                                                      -- 提交来源页面
    user_agent  text,                                                      -- 浏览器/设备信息
    status      text        not null default 'new',                        -- 处理状态
    created_at  timestamptz not null default current_timestamp,                        -- ⑤ 提交时间（自动）
    updated_at  timestamptz not null default current_timestamp,                        -- 最近变更时间

    -- 取值约束：反馈类型只能是这四种
    constraint ck_feedback_category
        check (category in ('bug', 'suggestion', 'content', 'other')),
    -- 取值约束：处理状态只能是这三种
    constraint ck_feedback_status
        check (status in ('new', 'read', 'resolved')),
    -- 取值约束：评分要么不填，要么 1-5
    constraint ck_feedback_rating
        check (rating is null or (rating between 1 and 5)),
    -- 取值约束：正文不能空白，且限长（防滥用）
    constraint ck_feedback_message
        check (char_length(btrim(message)) between 1 and 1000),
    -- 取值约束：称呼与联系方式限长
    constraint ck_feedback_name_len
        check (name is null or char_length(name) <= 60),
    constraint ck_feedback_contact_len
        check (contact is null or char_length(contact) <= 120),
    -- 取值约束：与主页主人的关系只能是这几种
    -- 注：已建好的库要把 online(网友) 改成 lover(恋人)，需另跑 db/migration_relation_lover.sql
    --     （check 约束不能就地改，必须 drop + add）
    constraint ck_feedback_relation
        check (relation is null or relation in
               ('classmate', 'friend', 'family', 'teacher', 'lover', 'other')),
    -- 取值约束：本条反馈针对的设备只能是这几种
    constraint ck_feedback_device
        check (device is null or device in
               ('phone', 'tablet', 'computer', 'other'))
);

comment on table  public.feedback            is '个人主页访客意见反馈';
comment on column public.feedback.name       is '① 名字或昵称（可空，页面默认署名「匿名访客」）';
comment on column public.feedback.relation   is '② 与主页主人的关系：classmate=同学 / friend=朋友 / family=家人 / teacher=老师 / lover=恋人 / other=其他';
comment on column public.feedback.device     is '③ 本条反馈针对的设备：phone=手机 / tablet=平板 / computer=电脑 / other=其他设备';
comment on column public.feedback.message    is '④ 反馈内容（必填，1-1000 字）';
comment on column public.feedback.created_at is '⑤ 提交时间（由数据库自动写入）';
comment on column public.feedback.category   is 'bug=问题 / suggestion=建议 / content=内容 / other=其他';
comment on column public.feedback.status     is 'new=未读 / read=已读 / resolved=已处理';


-- ------------------------------------------------------------
-- 2. 索引：支撑"按时间倒序看列表""按状态筛选"
-- ------------------------------------------------------------
create index if not exists idx_feedback_created_at on public.feedback (created_at desc);
create index if not exists idx_feedback_status     on public.feedback (status);


